#!/usr/bin/env python3
"""Generate the two complete appendix tables from saved overall summaries."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def table(method, folder, coefficient, symbol):
    source = ROOT / 'results' / folder / 'overall-aggregation.json'
    rows = json.loads(source.read_text())['conditions']
    rows.sort(key=lambda r: (r['layer'], r['scheme'] != 'layer-32',
                             r['word_set_type'] != 'non_contextualized',
                             r['policy'] != 'complete_only', r[coefficient]))
    assert len(rows) == 64
    lines = [
        f'% Source: results/{folder}/overall-aggregation.json',
        r'\begin{table*}[p]', r'\centering', r'\scriptsize',
        r'\setlength{\tabcolsep}{4pt}', r'\renewcommand{\arraystretch}{0.88}',
        r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}ccllcrr@{}}',
        r'\toprule',
        r'\shortstack{Readout\\layer} & \shortstack{Steered\\layer(s)} & Word bank & Token policy & $'
        + symbol + r'$ & MRR & MCS \\',
        r'\midrule',
    ]
    previous_layer = None
    for row in rows:
        if previous_layer is not None and row['layer'] != previous_layer:
            lines.append(r'\midrule')
        previous_layer = row['layer']
        steered = '32' if row['scheme'] == 'layer-32' else '29, 32, 35'
        bank = 'General' if row['word_set_type'] == 'non_contextualized' else 'Contextualized'
        policy = 'Complete only' if row['policy'] == 'complete_only' else 'Including proxies'
        scores = [f"${row['metrics'][m]['mean_delta']:+.7f}$" for m in ('mrr', 'cosine')]
        lines.append(' & '.join([str(row['layer']), steered, bank, policy,
                                 f"{row[coefficient]:g}", *scores]) + r' \\')
    lines.extend([
        r'\bottomrule', r'\end{tabular*}',
        r'\caption{' + method + ': all 64 evaluated configurations. MRR and MCS '
        r'columns report mean paired differences (steered minus unsteered), '
        r'averaged equally over twelve questions within each persona and then '
        r'equally over eight personas. Positive values indicate higher scores '
        r'under steering. Values are rounded to seven decimal places.}',
        r'\label{tab:quantitative-' + coefficient + r'-all}', r'\end{table*}', '',
    ])
    return '\n'.join(lines)


def main():
    output = ROOT / 'writeup' / 'tables' / 'quantitative_steering_results.tex'
    output.parent.mkdir(parents=True, exist_ok=True)
    text = (
        '% Generated by scripts/build_appendix_steering_tables.py; edit the builder to regenerate.\n'
        r'\subsection{Full Quantitative Steering Results}' '\n'
        r'\label{sec:full-quantitative-results}' '\n'
        r'Tables~\ref{tab:quantitative-alpha-all} and~\ref{tab:quantitative-beta-all} '
        r'list all configurations for additive alpha steering and band capping, '
        r'respectively. The MRR and MCS entries are differences from each experiment\textquotesingle s '
        r'own unsteered baseline, rather than absolute scores. Each entry averages '
        r'96 persona--question pairs, giving every question and persona equal weight. '
        r'General word banks depend only on the persona; contextualized banks also '
        r'depend on the question. The complete-only policy retains target words '
        r'represented by a complete token; the proxy-inclusive policy also permits '
        r'a representative token for a multi-token target word. All twelve questions '
        r'are included.\n' '\n'
    ).replace(r'\n', '\n')
    text += table('Alpha steering', 'mini-alpha-analysis', 'alpha', r'\alpha')
    text += '\n' + table('Band capping', 'mini-batch-cluster-readout', 'beta', r'\beta')
    output.write_text(text)
    print(f'Wrote {output}: 64 alpha rows and 64 band-capping rows.')


if __name__ == '__main__':
    main()
